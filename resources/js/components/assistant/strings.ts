/**
 * Everything the widget says in its own voice, as opposed to the answers.
 *
 * Both halves have to move together. A Kiswahili answer sitting under an
 * English "Need a person?" is half a translation, and half a translation reads
 * worse than none — it says the Kiswahili was a trick the machine did rather
 * than a language anybody here speaks.
 *
 * English is complete and is the base: every other language is written as a
 * partial and laid over it, so a word nobody has translated yet shows up in
 * English instead of as a blank. That is also what lets a language be added
 * with the dozen strings that matter first and filled in later.
 *
 * Languages beyond these twelve are still answered — the model writes in
 * whatever the visitor writes — and just wear English furniture.
 */

