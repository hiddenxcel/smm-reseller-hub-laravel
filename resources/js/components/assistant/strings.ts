const DICTIONARIES: Record<string, Partial2<Strings>> = { sw, fr, es, pt, ar, hi, tr, de, id, ru, zh };

/** English underneath, the visitor's language laid over it. */
export function t(locale: Locale): Strings {
    const over = DICTIONARIES[locale];

    if (!over) {
        return en;
    }

    return {
        ...en,
        ...(over as Partial<Strings>),
        quick: { ...en.quick, ...(over.quick ?? {}) },
        openers: { ...en.openers, ...(over.openers ?? {}) },
    } as Strings;
}

